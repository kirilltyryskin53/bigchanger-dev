function getLang() {
  return localStorage.getItem('bc_lang') || 'ru';
}

function setLang(lang) {
  localStorage.setItem('bc_lang', lang);
  applyTranslations(lang);
  document.dispatchEvent(new CustomEvent('bc:lang-change', { detail: lang }));
}

function t(key) {
  const lang = getLang();
  return translations[lang]?.[key] || translations.ru[key] || key;
}

function applyTranslations(lang = getLang()) {
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = translations[lang][el.dataset.i18n] || el.textContent;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = translations[lang][el.dataset.i18nPlaceholder] || el.placeholder;
  });
}

function initLanguageSwitcher() {
  applyTranslations();
  document.querySelectorAll('[data-lang]').forEach((btn) => {
    btn.addEventListener('click', () => setLang(btn.dataset.lang));
    btn.classList.toggle('active', btn.dataset.lang === getLang());
  });
  document.addEventListener('bc:lang-change', (e) => {
    document.querySelectorAll('[data-lang]').forEach((btn) => {
      btn.classList.toggle('active', btn.dataset.lang === e.detail);
    });
  });
}
